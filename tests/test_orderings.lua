local orderings = require("orderings")

local LAYOUT_A = "ParameterOrganizer layout 1\nplugin\tJS: phaser\nB\t0\tfreq\n"
local LAYOUT_B = "ParameterOrganizer layout 1\nplugin\tJS: phaser\nB\t0\tQ\nP\t1\t3\tleft Q\t\n"

test("a collection saves and loads back", function()
  local coll = orderings.new()
  orderings.add(coll, "By band", LAYOUT_A)
  orderings.add(coll, "Q first", LAYOUT_B)
  orderings.set_active(coll, "q FIRST")
  local back = orderings.parse(orderings.serialize(coll))
  check_equal(back.active, "Q first")
  check_equal(table.concat(orderings.names(back), ", "), "Original, By band, Q first")
  check_equal(orderings.text(back, "By band"), LAYOUT_A)
  check_equal(orderings.text(back, "Q first"), LAYOUT_B, "empty own-name field kept")
end)

test("Original is always there, has an empty layout and is the default", function()
  local coll = orderings.parse(nil)
  check_equal(coll.active, nil)
  check_equal(table.concat(orderings.names(coll), ", "), "Original")
  check_equal(orderings.text(coll, "Original"), orderings.EMPTY_LAYOUT)
  check_equal(orderings.text(coll, nil), orderings.EMPTY_LAYOUT)
  check_equal(orderings.is_original("original"), true)
end)

test("a layout saved before orderings becomes an active Ordering 1", function()
  local coll = orderings.parse(LAYOUT_A)
  check_equal(coll.active, "Ordering 1")
  check_equal(orderings.text(coll, "Ordering 1"), LAYOUT_A)
end)

test("names: Original is reserved, duplicates refused ignoring case", function()
  local coll = orderings.new()
  orderings.add(coll, "Ordering 1", LAYOUT_A)
  check_equal(orderings.can_use_name(coll, "original"), false)
  check_equal(orderings.can_use_name(coll, "ORDERING 1"), false)
  check_equal(orderings.can_use_name(coll, ""), false)
  check_equal(orderings.can_use_name(coll, "Mine"), true)
  check_equal(orderings.new_name(coll), "Ordering 2")
end)

test("copies get free names and can go at a position", function()
  local coll = orderings.new()
  orderings.add(coll, "A", LAYOUT_A)
  orderings.add(coll, "B", LAYOUT_B)
  check_equal(orderings.copy_name(coll, "A"), "A copy")
  orderings.add(coll, "A copy", LAYOUT_A, 2)
  check_equal(orderings.copy_name(coll, "A"), "A copy 2")
  check_equal(orderings.copy_name(coll, "Original"), "Original copy")
  check_equal(table.concat(orderings.names(coll), ", "), "Original, A, A copy, B")
end)

test("renaming the active ordering keeps it active", function()
  local coll = orderings.new()
  orderings.add(coll, "Ordering 1", LAYOUT_A)
  orderings.set_active(coll, "Ordering 1")
  orderings.rename(coll, "ordering 1", "Bands")
  check_equal(coll.active, "Bands")
  check_equal(orderings.text(coll, "Bands"), LAYOUT_A)
end)

test("removing the active ordering makes Original active", function()
  local coll = orderings.new()
  orderings.add(coll, "A", LAYOUT_A)
  orderings.add(coll, "B", LAYOUT_B)
  orderings.set_active(coll, "B")
  orderings.remove(coll, "B")
  check_equal(coll.active, nil)
  check_equal(table.concat(orderings.names(coll), ", "), "Original, A")
end)

test("only the active ordering's text changes", function()
  local coll = orderings.new()
  orderings.add(coll, "A", LAYOUT_A)
  orderings.add(coll, "B", LAYOUT_A)
  orderings.set_active(coll, "B")
  orderings.set_active_text(coll, LAYOUT_B)
  check_equal(orderings.text(coll, "A"), LAYOUT_A)
  check_equal(orderings.text(coll, "B"), LAYOUT_B)
end)
