local tree = require("tree")

-- root
--   Track 1
--     Phaser
--       Q          (branch, empty)
--       left Q attack (param)
--     EQ           (fx, empty)
--   Track 2
local function sample()
  local root = tree.new_node("root", "")
  local t1 = tree.add_child(root, tree.new_node("track", "Track 1"))
  local phaser = tree.add_child(t1, tree.new_node("fx", "Phaser"))
  local q = tree.add_child(phaser, tree.new_node("branch", "Q"))
  local p = tree.add_child(phaser, tree.new_node("param", "left Q attack", { index = 3 }))
  local eq = tree.add_child(t1, tree.new_node("fx", "EQ"))
  local t2 = tree.add_child(root, tree.new_node("track", "Track 2"))
  return { root = root, t1 = t1, phaser = phaser, q = q, p = p, eq = eq, t2 = t2 }
end

local function label_of(cursor)
  local node = tree.focused(cursor)
  return node and node.label or "empty"
end

test("new cursor focuses the first item", function()
  local s = sample()
  local c = tree.new_cursor(s.root)
  check_equal(label_of(c), "Track 1")
  check_equal(select(2, tree.position(c)), 2, "count")
end)

test("up and down stop at the edges", function()
  local s = sample()
  local c = tree.new_cursor(s.root)
  check_equal(tree.move_prev(c), false, "prev at top")
  check_equal(tree.move_next(c), true)
  check_equal(label_of(c), "Track 2")
  check_equal(tree.move_next(c), false, "next at bottom")
  check_equal(label_of(c), "Track 2")
end)

test("home and end", function()
  local s = sample()
  local c = tree.new_cursor(s.phaser)
  tree.move_last(c)
  check_equal(label_of(c), "left Q attack")
  tree.move_first(c)
  check_equal(label_of(c), "Q")
end)

test("right enters and focuses the first child; left returns", function()
  local s = sample()
  local c = tree.new_cursor(s.root)
  check_equal(tree.enter(c), true)
  check_equal(label_of(c), "Phaser")
  tree.move_next(c)
  check_equal(label_of(c), "EQ")
  check_equal(tree.leave(c), true)
  check_equal(label_of(c), "Track 1")
end)

test("left at the top level does nothing", function()
  local s = sample()
  local c = tree.new_cursor(s.root)
  check_equal(tree.leave(c), false)
  check_equal(label_of(c), "Track 1")
end)

test("right on a parameter does nothing", function()
  local s = sample()
  local c = tree.new_cursor(s.phaser)
  tree.move_last(c)
  check_equal(tree.enter(c), false)
  check_equal(label_of(c), "left Q attack")
end)

test("an empty branch can be entered onto the empty position", function()
  local s = sample()
  local c = tree.new_cursor(s.phaser)
  check_equal(tree.enter(c), true)
  check_equal(c.container, s.q, "container")
  check_equal(label_of(c), "empty")
  check_equal(tree.move_next(c), false, "next on empty")
  check_equal(tree.move_prev(c), false, "prev on empty")
  check_equal(tree.move_first(c), false, "home on empty")
  check_equal(tree.leave(c), true)
  check_equal(label_of(c), "Q")
end)

test("insert on the empty position creates the first item", function()
  local s = sample()
  local c = tree.new_cursor(s.phaser)
  tree.enter(c)
  tree.insert_after_focus(c, tree.new_node("branch", "attack"))
  check_equal(label_of(c), "attack")
  check_equal(#s.q.children, 1, "children")
  check_equal(s.q.children[1].parent, s.q, "parent")
end)

test("insert goes right after the focused item, at the same level", function()
  local s = sample()
  local c = tree.new_cursor(s.phaser)
  tree.insert_after_focus(c, tree.new_node("branch", "frequency"))
  check_equal(label_of(c), "frequency")
  check_equal(s.phaser.children[1].label, "Q")
  check_equal(s.phaser.children[2].label, "frequency")
  check_equal(s.phaser.children[3].label, "left Q attack")
  check_equal(#s.q.children, 0, "nothing inside Q")
end)

test("pasting a placed parameter moves it", function()
  local s = sample()
  local c = tree.new_cursor(s.phaser)
  tree.enter(c)
  tree.insert_after_focus(c, s.p)
  check_equal(s.p.parent, s.q, "new parent")
  check_equal(#s.phaser.children, 1, "phaser children")
  check_equal(label_of(c), "left Q attack")
end)

test("moving within one level keeps the focus index right", function()
  local root = tree.new_node("branch", "level")
  local a = tree.add_child(root, tree.new_node("param", "a"))
  tree.add_child(root, tree.new_node("param", "b"))
  tree.add_child(root, tree.new_node("param", "c"))
  local c = tree.new_cursor(root)
  tree.move_last(c)
  tree.insert_after_focus(c, a)
  check_equal(root.children[1].label, "b")
  check_equal(root.children[2].label, "c")
  check_equal(root.children[3].label, "a")
  check_equal(label_of(c), "a")
end)

test("pasting the focused node onto itself changes nothing", function()
  local s = sample()
  local c = tree.new_cursor(s.phaser)
  tree.insert_after_focus(c, s.q)
  check_equal(s.phaser.children[1], s.q)
  check_equal(#s.phaser.children, 2, "children")
end)

test("a branch cannot be moved inside itself", function()
  local s = sample()
  local c = tree.new_cursor(s.phaser)
  tree.enter(c)
  check_equal(tree.insert_after_focus(c, s.q), nil)
  check_equal(s.q.parent, s.phaser, "parent unchanged")
end)

test("delete focuses the next item, then the previous, then empty", function()
  local s = sample()
  local c = tree.new_cursor(s.phaser)
  check_equal(tree.remove_focused(c), s.q)
  check_equal(label_of(c), "left Q attack")
  check_equal(tree.remove_focused(c), s.p)
  check_equal(label_of(c), "empty")
  check_equal(tree.remove_focused(c), nil)
end)

test("delete on the last item focuses the previous one", function()
  local s = sample()
  local c = tree.new_cursor(s.phaser)
  tree.move_last(c)
  tree.remove_focused(c)
  check_equal(label_of(c), "Q")
end)

test("type-ahead finds the next match and wraps", function()
  local root = tree.new_node("branch", "level")
  for _, l in ipairs({ "attack", "frequency", "Attack 2", "mix" }) do
    tree.add_child(root, tree.new_node("branch", l))
  end
  local c = tree.new_cursor(root)
  check_equal(tree.jump_to_letter(c, "a"), true)
  check_equal(label_of(c), "Attack 2")
  tree.jump_to_letter(c, "A")
  check_equal(label_of(c), "attack")
  check_equal(tree.jump_to_letter(c, "z"), false)
  check_equal(label_of(c), "attack")
end)

test("enclosing and ancestors", function()
  local s = sample()
  check_equal(tree.enclosing(s.p, "fx"), s.phaser)
  check_equal(tree.enclosing(s.p, "track"), s.t1)
  local up = tree.ancestors(s.p)
  check_equal(#up, 3, "ancestor count")
  check_equal(up[1], s.phaser)
  check_equal(up[3], s.root)
end)

test("walk finds a node", function()
  local s = sample()
  local found = tree.walk(s.root, function(n) return n.data.index == 3 end)
  check_equal(found, s.p)
end)
